import 'word_list.dart';

/// A named pool of answers the player can choose between.
///
/// The five-letter game gave a player nothing to go on: a word could be any of
/// 766 things. Choosing a topic first turns the opening guess from a shot in
/// the dark into a reasonable one — someone who picks Cricket already knows the
/// answer is cricket vocabulary, which is most of the difficulty gone before a
/// single letter is typed.
class WordTopic {
  const WordTopic({
    required this.id,
    required this.name,
    required this.emoji,
    required this.words,
  });

  final String id;
  final String name;
  final String emoji;
  final List<String> words;

  /// Answers are stored lower-case for readability and played upper-case.
  List<String> get answers => words;
}

